export const PROCUREMENT_POLICY_TITLE = "Procedimiento de compras (ejemplo)";

export const PROCUREMENT_POLICY_TEXT = `PROPÓSITO
Adquirir los productos y servicios que necesitan las áreas, con calidad, oportunidad y al mejor costo.

ALCANCE
Aplica a todas las compras de bienes y servicios de la organización.

DEFINICIONES
Solicitud de compra: requerimiento de un área. Cotización: oferta de un proveedor. Cuadro comparativo: comparación de cotizaciones.

RELACIONES CLAVES Y RESPONSABILIDADES
El área solicitante describe la necesidad; Compras cotiza, selecciona y registra; el aprobador autoriza según el monto.

BUENAS PRÁCTICAS Y ACUERDOS
Comparar al menos tres cotizaciones cuando el monto lo exija, verificar la documentación del proveedor y conservar los soportes.

DESARROLLO
1. El área registra la solicitud.
2. Compras cotiza y elabora el cuadro comparativo cuando aplique.
3. Se aprueba según el monto y se emite la orden.
4. Se recibe el pedido, se legaliza y se radica la factura.
`;
